const dynamicBisaya = [
  [/^Page (\d+) of (\d+)$/, 'Panid $1 sa $2'],
  [/^Showing (\d+) lawyers?$/, 'Nagpakita og $1 ka abogado'],
  [/^Showing (\d+) cases?$/, 'Nagpakita og $1 ka kaso'],
  [/^(\d+) minutes ago$/, '$1 ka minuto ang milabay'],
  [/^(\d+) hours? ago$/, '$1 ka oras ang milabay'],
  [/^(\d+) days? ago$/, '$1 ka adlaw ang milabay'],
  [/^Loading (.+)\.\.\.$/, 'Nag-load sa $1...'],
];

export const translateText = (text, language = 'en') => {
  if (language !== 'ceb' || typeof text !== 'string') return text;

  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const leading = match?.[1] || '';
  const value = match?.[2] || text;
  const trailing = match?.[3] || '';
  if (!value) return text;

  if (bisaya[value]) return `${leading}${bisaya[value]}${trailing}`;

  for (const [pattern, replacement] of dynamicBisaya) {
    if (pattern.test(value)) {
      return `${leading}${value.replace(pattern, replacement)}${trailing}`;
    }
  }

  return text;
};

export const translations = { en: {}, ceb: bisaya };
